    def _check_port_direction(self):
        mismatches = []
        for swc_type in ATOMIC_SWC_TYPES:
          for swc in self.root.iter(self._ns(swc_type)):
            sn = self._sn(swc)
            ptm = {}
            ports = swc.find(self._ns("PORTS"))
            if ports is None:
                continue
            for pp in ports.findall(self._ns("P-PORT-PROTOTYPE")):
                p = self._bp(pp)
                if p:
                    ptm[p] = 'P'
            for rp in ports.findall(self._ns("R-PORT-PROTOTYPE")):
                p = self._bp(rp)
                if p:
                    ptm[p] = 'R'
            if not ptm:
                continue
            beh = swc.find(self._ns("INTERNAL-BEHAVIORS"))
            if beh is None:
                beh = swc.find(self._ns("SWC-INTERNAL-BEHAVIOR"))
            if beh is None:
                continue
            for re_elem in beh.iter(self._ns("RUNNABLE-ENTITY")):
                rn = self._sn(re_elem)
                dr = re_elem.find(self._ns("DATA-RECEIVE-POINT-BY-ARGUMENTS"))
                if dr is not None:
                    for pt in dr.iter(self._ns("PORT-PROTOTYPE-TREF")):
                        if pt.text and ptm.get(pt.text.strip()) == 'P':
                            mismatches.append(f"'{sn}' '{rn}': RECEIVE→P-Port")
                ds = re_elem.find(self._ns("DATA-SEND-POINTS"))
                if ds is not None:
                    for pt in ds.iter(self._ns("PORT-PROTOTYPE-TREF")):
                        if pt.text and ptm.get(pt.text.strip()) == 'R':
                            mismatches.append(f"'{sn}' '{rn}': SEND→R-Port")
        if not mismatches:
            self.r.passed("Port 方向一致")
        else:
            self.r.error(f"{len(mismatches)} 个方向不匹配")
            for x in mismatches:
                self.r.error(f"  {x}")
        # P2b: Port INTERFACE-TREF 存在性 + 目标存在性
        port_issues = 0
        tref_unresolved = 0
        for swc_type in ATOMIC_SWC_TYPES:
          for swc in self.root.iter(self._ns(swc_type)):
            sn = self._sn(swc)
            ports = swc.find(self._ns("PORTS"))
            if ports is None:
                continue
            for pp in ports.findall(self._ns("P-PORT-PROTOTYPE")):
                it = pp.find(self._ns("PROVIDED-INTERFACE-TREF"))
                if it is None or not it.text:
                    port_issues += 1
                    if port_issues <= 5:
                        pn = self._sn(pp)
                        self.r.warning(f"P-Port '{pn}' 缺 PROVIDED-INTERFACE-TREF{self._li(pp)}")
                elif it.text.strip() and not self._resolvable(it.text.strip(), self.paths):
                    tref_unresolved += 1
                    self.r.error(f"SWC '{sn}' P-Port PROVIDED-INTERFACE-TREF 引用未定义: '{it.text.strip()}'{self._li(swc)}")
            for rp in ports.findall(self._ns("R-PORT-PROTOTYPE")):
                it = rp.find(self._ns("REQUIRED-INTERFACE-TREF"))
                if it is None or not it.text:
                    port_issues += 1
                    if port_issues <= 5:
                        pn = self._sn(rp)
                        self.r.warning(f"R-Port '{pn}' 缺 REQUIRED-INTERFACE-TREF{self._li(rp)}")
                elif it.text.strip() and not self._resolvable(it.text.strip(), self.paths):
                    tref_unresolved += 1
                    self.r.error(f"SWC '{sn}' R-Port REQUIRED-INTERFACE-TREF 引用未定义: '{it.text.strip()}'{self._li(swc)}")
        if port_issues == 0:
            self.r.passed("Port INTERFACE-TREF 完整")
        if tref_unresolved == 0:
            self.r.passed("Port INTERFACE-TREF 目标均存在")

    def _check_runnable(self):
        rc = 0
        sym_missing = 0
        # P1b: RUNNABLE-ENTITY 完整元素顺序 (XSD group继承: REFERRABLE→IDENTIFIABLE→EXECUTABLE-ENTITY→RUNNABLE-ENTITY, 34个)
        runnable_order = [
            "SHORT-NAME", "SHORT-NAME-FRAGMENTS", "LONG-NAME", "DESC", "CATEGORY",
            "ADMIN-DATA", "INTRODUCTION", "ANNOTATIONS",
            "ACTIVATION-REASONS", "CAN-ENTER-EXCLUSIVE-AREA-REFS", "EXCLUSIVE-AREA-NESTING-ORDER-REFS",
            "MINIMUM-START-INTERVAL", "REENTRANCY-LEVEL", "RUNS-INSIDE-EXCLUSIVE-AREA-REFS", "SW-ADDR-METHOD-REF",
            "ARGUMENTS", "ASYNCHRONOUS-SERVER-CALL-RESULT-POINTS", "CAN-BE-INVOKED-CONCURRENTLY",
            "DATA-READ-ACCESSS", "DATA-RECEIVE-POINT-BY-ARGUMENTS", "DATA-RECEIVE-POINT-BY-VALUES",
            "DATA-SEND-POINTS", "DATA-WRITE-ACCESSS", "EXTERNAL-TRIGGERING-POINTS", "INTERNAL-TRIGGERING-POINTS",
            "MODE-ACCESS-POINTS", "MODE-SWITCH-POINTS", "PARAMETER-ACCESSS",
            "READ-LOCAL-VARIABLES", "SERVER-CALL-POINTS", "SYMBOL", "WAIT-POINTS",
            "WRITTEN-LOCAL-VARIABLES", "VARIATION-POINT",
        ]
        for re_elem in self.root.iter(self._ns("RUNNABLE-ENTITY")):
            rc += 1
            rn = self._sn(re_elem)
            # P2c: SYMBOL 存在性检查
            sym = re_elem.find(self._ns("SYMBOL"))
            if sym is None:
                sym_missing += 1
                self.r.error(f"Runnable '{rn}' 缺 SYMBOL (XSD: minOccurs=1){self._li(re_elem)}")
            elif not sym.text or not sym.text.strip():
                sym_missing += 1
                self.r.error(f"Runnable '{rn}' SYMBOL 为空{self._li(re_elem)}")
            # P1b: 元素顺序检查
            children = [self._lt(c.tag) for c in re_elem]
            order_idx = {tag: i for i, tag in enumerate(runnable_order)}
            prev_idx = -1
            for ch in children:
                if ch in order_idx:
                    ci = order_idx[ch]
                    if ci < prev_idx:
                        self.r.warning(f"Runnable '{rn}' 元素顺序违规: '{ch}' 出现在其后的元素之前{self._li(re_elem)}")
                        break
                    prev_idx = ci
        if rc > 0:
            self.r.passed(f"{rc} 个 Runnable")
        else:
            self.r.info("无 Runnable")
        if sym_missing > 0:
            self.r.error(f"{sym_missing} 个 Runnable 缺少 SYMBOL")


    def _check_constant_spec(self):
        """检查 ConstantSpecification 是否具备取值定义。

        AUTOSAR CP 常用 VALUE-SPEC；缺 VALUE-SPEC 时恒润会报
        ASW_ERROR_TYPE_0002: Constant is null。
        亦接受 VALUE-REF / VALS / VALUE / CONSTANT-REFERENCE-REF。
        """
        cc = 0
        empty_issues = 0
        ref_issues = 0
        for cs in self.root.iter(self._ns("CONSTANT-SPECIFICATION")):
            cc += 1
            n = self._sn(cs)
            vs = cs.find(self._ns("VALUE-SPEC"))
            vr = cs.find(self._ns("VALUE-REF"))
            vals = cs.find(self._ns("VALS"))
            ns = cs.find(self._ns("VALUE"))
            nested = cs.find(self._ns("CONSTANT-REFERENCE-REF"))

            has_value_spec = vs is not None and len(list(vs)) > 0
            has_value_ref = vr is not None and bool((vr.text or "").strip())
            has_vals = vals is not None and len(vals) > 0
            has_value = ns is not None
            has_nested = nested is not None

            if not (has_value_spec or has_value_ref or has_vals or has_value or has_nested):
                empty_issues += 1
                detail = "VALUE-SPEC 为空" if vs is not None else "缺 VALUE-SPEC"
                self.r.error(
                    f"ConstantSpecification '{n}' {detail} "
                    f"(恒润 ASW_ERROR_TYPE_0002: Constant is null)"
                    f"{self._li(vs if vs is not None else cs)}"
                )

            if has_value_ref and not self._resolvable(vr.text.strip(), self.paths):
                ref_issues += 1
                self.r.error(
                    f"ConstantSpecification '{n}' VALUE-REF 引用未定义{self._li(cs)}"
                )


        if cc == 0:
            self.r.info("文件中无 CONSTANT-SPECIFICATION")
        elif empty_issues == 0 and ref_issues == 0:
            self.r.passed(f"{cc} 个 ConstantSpecification")
        else:
            self.r.info(
                f"ConstantSpecification: 共 {cc} 个, "
                f"缺VALUE-SPEC={empty_issues}, VALUE-REF无效={ref_issues}"
            )

    def _check_init_value_type(self):
        """检查初始值类型兼容性 (Vector 40360)"""
        issues = 0
        checked = 0
        
        # 构建 ConstantSpecification 路径到数据元素的映射
        # 用于检查 CATEGORY 与数据类型的兼容性
        cs_to_data_elements = {}  # cs_path -> [(data_elem_sn, type_tref_dest, type_tref_path)]
        for vdp in self.root.iter(self._ns("VARIABLE-DATA-PROTOTYPE")):
            vdp_sn = self._sn(vdp)
            init_val = vdp.find(self._ns("INIT-VALUE"))
            if init_val is None:
                continue
            const_ref = init_val.find(self._ns("CONSTANT-REFERENCE"))
            if const_ref is None:
                continue
            const_ref_elem = const_ref.find(self._ns("CONSTANT-REF"))
            if const_ref_elem is None or not const_ref_elem.text:
                continue
            cs_path = const_ref_elem.text.strip()
            
            # 获取 TYPE-TREF
            type_tref = vdp.find(self._ns("TYPE-TREF"))
            if type_tref is None or not type_tref.text:
                continue
            type_dest = type_tref.get("DEST", "")
            type_path = type_tref.text.strip()
            
            if cs_path not in cs_to_data_elements:
                cs_to_data_elements[cs_path] = []
            cs_to_data_elements[cs_path].append((vdp_sn, type_dest, type_path))
        
        # 1) 检查 CONSTANT-SPECIFICATION 的 VALUE-SPEC
        for cs in self.root.iter(self._ns("CONSTANT-SPECIFICATION")):
            cs_name = self._sn(cs)
            cs_path = self._bp(cs)
            vs = cs.find(self._ns("VALUE-SPEC"))
            if vs is None:
                continue
            
            # Vector 40360: 只看 VALUE-SPEC 的直接子形态，不能递归扫字段里的 CATEGORY。
            # RECORD/ARRAY-VALUE-SPECIFICATION 内字段使用 CATEGORY=VALUE 是合法的。
            if cs_path in cs_to_data_elements:
                top_avs = vs.find(self._ns("APPLICATION-VALUE-SPECIFICATION"))
                top_rvs = vs.find(self._ns("RECORD-VALUE-SPECIFICATION"))
                top_arr = vs.find(self._ns("ARRAY-VALUE-SPECIFICATION"))
                for data_sn, type_dest, type_path in cs_to_data_elements[cs_path]:
                    if type_dest != "APPLICATION-RECORD-DATA-TYPE":
                        continue
                    if top_rvs is not None or top_arr is not None:
                        continue
                    if top_avs is None:
                        continue
                    cat_elem = top_avs.find(self._ns("CATEGORY"))
                    category = (cat_elem.text or "").strip() if cat_elem is not None else ""
                    if category.upper() == "VALUE":
                        issues += 1
                        self.r.error(
                            f"ConstantSpecification '{cs_name}' CATEGORY=VALUE "
                            f"但数据元素 '{data_sn}' 的类型为 RECORD ({type_path}) "
                            f"(Vector 40360){self._li(top_avs)}"
                        )

            # 检查 APPLICATION-VALUE-SPECIFICATION（含 RECORD 字段）的取值形态
            for avs in vs.iter(self._ns("APPLICATION-VALUE-SPECIFICATION")):
                checked += 1
                cat_elem = avs.find(self._ns("CATEGORY"))
                category = (cat_elem.text or "").strip() if cat_elem is not None else ""

                # 检查 SW-VALUE-CONT 中的值
                swc = avs.find(self._ns("SW-VALUE-CONT"))
                if swc is None:
                    continue

                sw_values_phys = swc.find(self._ns("SW-VALUES-PHYS"))
                if sw_values_phys is None:
                    continue

                for v_elem in sw_values_phys.findall(self._ns("V")):
                    v_text = (v_elem.text or "").strip()
                    # 检查值是否与 category 兼容
                    if category.upper() == "VALUE":
                        # VALUE category 应该是数值
                        try:
                            float(v_text)
                        except ValueError:
                            if v_text not in ("", "true", "false", "TRUE", "FALSE"):
                                issues += 1
                                if issues <= 10:
                                    self.r.warning(f"ConstantSpecification '{cs_name}' CATEGORY=VALUE 但值 '{v_text}' 非数值{self._li(v_elem)}")
                    elif category.upper() in ("TEXT", "STRING"):
                        # TEXT category 应该是字符串，任何值都可以
                        pass
                    elif category.upper() in ("BOOLEAN", "BOOL"):
                        # BOOLEAN category 应该是 true/false
                        if v_text.lower() not in ("true", "false", "0", "1"):
                            issues += 1
                            if issues <= 10:
                                self.r.warning(f"ConstantSpecification '{cs_name}' CATEGORY=BOOLEAN 但值 '{v_text}' 非布尔{self._li(v_elem)}")
        
        # 2) 检查 INIT-VALUE 中的直接值定义
        for iv in self.root.iter(self._ns("INIT-VALUE")):
            # 检查 NUMERICAL-VALUE-SPECIFICATION
            for nvs in iv.iter(self._ns("NUMERICAL-VALUE-SPECIFICATION")):
                checked += 1
                for v_elem in nvs.iter(self._ns("V")):
                    v_text = (v_elem.text or "").strip()
                    try:
                        float(v_text)
                    except ValueError:
                        if v_text:
                            issues += 1
                            if issues <= 10:
                                self.r.warning(f"INIT-VALUE 中 NUMERICAL-VALUE-SPECIFICATION 包含非数值 '{v_text}'{self._li(v_elem)}")
            
            # 检查 TEXT-VALUE-SPECIFICATION
            for tvs in iv.iter(self._ns("TEXT-VALUE-SPECIFICATION")):
                checked += 1
                # TEXT 值应该是字符串，无需特殊检查
            
            # 检查 BOOLEAN-VALUE-SPECIFICATION
            for bvs in iv.iter(self._ns("BOOLEAN-VALUE-SPECIFICATION")):
                checked += 1
                for v_elem in bvs.iter(self._ns("V")):
                    v_text = (v_elem.text or "").strip()
                    if v_text.lower() not in ("true", "false", "0", "1", ""):
                        issues += 1
                        if issues <= 10:
                            self.r.warning(f"INIT-VALUE 中 BOOLEAN-VALUE-SPECIFICATION 值 '{v_text}' 非布尔{self._li(v_elem)}")
        
        if checked == 0:
            self.r.info("无初始值定义")
        elif issues == 0:
            self.r.passed(f"{checked} 个初始值类型兼容")


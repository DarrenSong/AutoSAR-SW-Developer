#  批量校验
# ══════════════════════════════════════════════════════════════════════════════
def batch_validate(directory: str, xsd_path: str, output_dir: str, pdf: bool = False):
    """批量校验目录下所有 ARXML 文件"""
    arxml_files = []
    for f in sorted(os.listdir(directory)):
        if f.lower().endswith('.arxml'):
            arxml_files.append(os.path.join(directory, f))

    if not arxml_files:
        print(f"目录 {directory} 下无 .arxml 文件")
        return

    print(f"\n{'='*72}")
    print(f"  批量校验: {directory}")
    print(f"  文件数: {len(arxml_files)}")
    print(f"{'='*72}\n")

    results = []
    for i, fp in enumerate(arxml_files, 1):
        fn = os.path.basename(fp)
        print(f"\n[{i}/{len(arxml_files)}] {fn}")
        print("-" * 50)
        v = AutosarSchemaValidator(fp, xsd_path)
        r = v.validate()
        results.append((fn, r, v))

    # 汇总
    print(f"\n{'='*72}")
    print(f"  批量校验汇总")
    print(f"{'='*72}")
    total_err = 0
    total_warn = 0
    for fn, r, v in results:
        status = "PASS" if r.is_valid else "FAIL"
        print(f"  [{status}] {fn}: {len(r.errors)} 错误, {len(r.warnings)} 警告")
        total_err += len(r.errors)
        total_warn += len(r.warnings)
    print(f"\n  总计: {total_err} 错误, {total_warn} 警告")
    print(f"{'='*72}\n")

    # 导出报告
    if output_dir:
        os.makedirs(output_dir, exist_ok=True)
        for fn, r, v in results:
            base = os.path.splitext(fn)[0]
            txt_out = os.path.join(output_dir, f"{base}_validation_report.txt")
            v.export_txt(txt_out)
            if pdf:
                pdf_out = os.path.join(output_dir, f"{base}_validation_report.pdf")
                v.export_pdf(pdf_out)



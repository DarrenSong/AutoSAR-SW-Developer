                                if is_bf:
                                    mask_elem = sc.find(self._ns("MASK"))
                                    mask_val = mask_elem.text.strip() if mask_elem is not None and mask_elem.text else ''
                                    key = (mask_val, vv)
                                else:
                                    key = vv

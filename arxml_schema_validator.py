    # ══════════════════════════════════════════════════════════════════════════
    #  Phase 1: 文件层校验
    # ══════════════════════════════════════════════════════════════════════════
    def _check_file(self):
        if not os.path.isfile(self.filepath):
            self.r.error(f"文件不存在: {self.filepath}")
            return
        sz = os.path.getsize(self.filepath) / (1024 * 1024)
        self.r.passed(f"文件存在 ({sz:.2f} MB)")
        if not self.filepath.lower().endswith('.arxml'):
            self.r.warning("文件后缀非 .arxml")

    def _check_encoding(self):
        try:
            with open(self.filepath, 'rb') as f:
                bom = f.read(3)
            if bom[:3] == b'\xef\xbb\xbf':
                self.r.warning("UTF-8 BOM 存在 (规范要求无 BOM, TPS_ASR_00006)")
            elif bom[:2] in (b'\xff\xfe', b'\xfe\xff'):
                self.r.error("文件为 UTF-16 编码 (规范要求 UTF-8)")
            else:
                self.r.passed("UTF-8 无 BOM")

            with open(self.filepath, 'r', encoding='utf-8') as f:
                first_line = f.readline()
            if 'encoding=' in first_line:
                self.r.passed("XML 声明含 encoding")
            else:
                self.r.warning("XML 声明未指定 encoding")
            if 'version="1.0"' in first_line or "version='1.0'" in first_line:
                self.r.passed("XML 版本为 1.0")
            elif 'version=' in first_line:
                self.r.warning("XML 版本非 1.0 (规范要求 XML 1.0)")
        except Exception as e:
            self.r.warning(f"编码检查失败: {e}")

    # ══════════════════════════════════════════════════════════════════════════
    #  Phase 2: XML 解析
    # ══════════════════════════════════════════════════════════════════════════
    def _parse_xml(self):
        try:
            from lxml import etree
        except ImportError:
            self.r.error("未安装 lxml, 无法解析 XML (pip install lxml)")
            return
        try:
            with open(self.filepath, 'rb') as f:
                raw = f.read()
            if raw[:3] == b'\xef\xbb\xbf':
                raw = raw[3:]
            # 使用 lxml 解析, 保留 sourceline 行号信息
            self.root = etree.fromstring(raw, base_url=self.filepath)
            self.r.passed("XML well-formed")
            # 读取文件行 & 构建行号映射
            with open(self.filepath, 'r', encoding='utf-8-sig') as f:
                self.file_lines = f.readlines()
            for ln, line in enumerate(self.file_lines, 1):
                m = re.search(r'<SHORT-NAME>([^<]+)</SHORT-NAME>', line)
                if m:
                    self.line_map[m.group(1).strip()] = ln
        except etree.ParseError as e:
            self.r.error(f"XML 解析错误: {e}")
        except Exception as e:
            self.r.error(f"XML 解析错误: {e}")

    # ══════════════════════════════════════════════════════════════════════════
    #  Phase 3: XSD Schema 校验 (lxml)
    # ══════════════════════════════════════════════════════════════════════════
    def _check_xsd_schema(self):
        if not self.xsd_path or not os.path.isfile(self.xsd_path):
            expect = self.xsd_path or "(未指定路径)"
            self.r.warning(
                f"XSD 文件未找到, 跳过 Schema 校验 — 期望: {expect}"
            )
            return

        try:
            from lxml import etree
        except ImportError:
            self.r.warning("未安装 lxml, 跳过 XSD Schema 校验 (pip install lxml)")
            return

        try:
            # 解析 XSD
            xsd_tree = etree.parse(self.xsd_path)
            schema = etree.XMLSchema(xsd_tree)

            # 复用 _parse_xml 已解析的 self.root (已包含 sourceline)
            # 校验
            if schema.validate(self.root):
                self.r.passed("XSD Schema 校验通过 (符合 AUTOSAR_00046 规范)")
            else:
                err_count = 0
                for err in schema.error_log:
                    err_count += 1
                    self.r.error(f"XSD L{err.line}: {err.message}")
                    # 显示对应行的文件内容, 帮助定位组件
                    if 0 < err.line <= len(self.file_lines):
                        line_content = self.file_lines[err.line - 1].strip()
                        self.r.detail(f"         内容: {line_content}")
                self.r.xsd_errors = [str(e) for e in schema.error_log]
                # 构建 XSD 已报的 SHORT-NAME 超长集合 (用于语义检查去重)
                self.xsd_long_names = set()
                for err in schema.error_log:
                    if 'maxLength' in err.message and 'SHORT-NAME' in err.message:
                        if 0 < err.line <= len(self.file_lines):
                            m = re.search(r'<SHORT-NAME>([^<]+)</SHORT-NAME>', self.file_lines[err.line - 1])
                            if m:
                                self.xsd_long_names.add(m.group(1).strip())
                self.r.warning(f"XSD Schema 校验失败: {err_count} 个错误")
        except Exception as e:
            self.r.warning(f"XSD 校验异常: {e}")

    # ══════════════════════════════════════════════════════════════════════════
    #  Phase 4: 构建索引
    # ══════════════════════════════════════════════════════════════════════════
    def _build_index(self):
        # 将 iter() 结果存为列表, 确保 lxml 元素对象引用稳定
        # (lxml 每次 iter() 调用会创建新的 Python 包装对象, id() 不稳定)
        all_elems = list(self.root.iter())

        # 父元素映射
        self.parent_map = {}
        for p in all_elems:
            for c in p:
                self.parent_map[id(c)] = p

        # 路径集合 - 为每个元素缓存路径, 确保中间元素(无SHORT-NAME)也能传递父路径
        path_cache = {}  # id(elem) -> path
        self.path_last = {}  # last-component -> set of full paths (用于快速查找)
        for e in all_elems:
            p = self.parent_map.get(id(e))
            parent_path = path_cache.get(id(p), "") if p is not None else ""
            s = e.find(self._ns("SHORT-NAME"))
            if s is not None and s.text and s.text.strip():
                sn = s.text.strip()
                full_path = f"{parent_path}/{sn}" if parent_path else f"/{sn}"
                path_cache[id(e)] = full_path
                self.paths.add(full_path)
                self.path_tag[full_path] = self._lt(e.tag)
                # 构建 last-component 索引
                if sn not in self.path_last:
                    self.path_last[sn] = set()
                self.path_last[sn].add(full_path)
            else:
                # 无 SHORT-NAME 的元素也缓存路径, 供子元素使用
                path_cache[id(e)] = parent_path

    # ══════════════════════════════════════════════════════════════════════════
    #  Phase 5: 语义校验
    # ══════════════════════════════════════════════════════════════════════════
    def _check_root_namespace(self):
        exp = f"{{{AUTOSAR_NS}}}AUTOSAR"
        if self.root.tag == exp:
            self.r.passed("根元素 AUTOSAR, 命名空间正确")
        else:
            self.r.error(f"根元素错误: {self.root.tag} (期望 {exp})")

        sl = self.root.attrib.get(f"{{{XSI_NS}}}schemaLocation", "")
        if sl:
            ps = sl.split()
            if len(ps) >= 2 and ps[0] == AUTOSAR_NS:
                self.r.passed("xsi:schemaLocation 格式正确")
            else:
                self.r.warning("schemaLocation 格式异常")
        else:
            self.r.warning("缺少 xsi:schemaLocation")

    def _check_schema_version(self):
        sl = self.root.attrib.get(f"{{{XSI_NS}}}schemaLocation", "")
        if not sl:
            return
        ps = sl.split()
        if len(ps) < 2:
            return
        sf = ps[1]
        m = re.search(r'AUTOSAR_(\d+)-(\d+)-(\d+)\.xsd', sf)
        if m:
            a, b, c = int(m.group(1)), int(m.group(2)), int(m.group(3))
            self.r.info(f"Schema 版本: {a}.{b}.{c}")
            if a == 4 and b > 4:
                self.r.warning(f"版本 4.{b}.{c} 较高, 部分工具可能不兼容")
        elif re.search(r'AUTOSAR_R\d+', sf):
            self.r.info("使用 Rxx 版本格式")
        elif re.search(r'AUTOSAR_\d{5}\.xsd', sf):
            self.r.info("使用 00047 兼容格式")

    def _check_packages(self):
        ap = self.root.find(self._ns("AR-PACKAGES"))
        if ap is None:
            ap = self.root.find(self._ns("TOP-LEVEL-PACKAGES"))
            if ap is not None:
                self.r.warning("使用旧版 TOP-LEVEL-PACKAGES")
            else:
                self.r.error("缺少 AR-PACKAGES")
                return
        pkgs = ap.findall(self._ns("AR-PACKAGE"))
        if not pkgs:
            self.r.error("AR-PACKAGES 中无 AR-PACKAGE")
            return
        self.r.passed(f"{len(pkgs)} 个顶层包")
        seen = set()
        names = []
        for p in pkgs:
            n = self._sn(p)
            if n == "?":
                self.r.error("AR-PACKAGE 缺 SHORT-NAME")
                continue
            names.append(n)
            if n in seen:
                self.r.error(f"顶层包名重复: '{n}'")
            seen.add(n)
        self.r.info(f"包: {', '.join(names[:10])}")

    def _check_naming(self):
        violations = 0
        long_violations = 0
        xsd_long = getattr(self, 'xsd_long_names', set())
        for e in self.root.iter():
            s = e.find(self._ns("SHORT-NAME"))
            if s is not None and s.text:
                n = s.text.strip()
                if not SHORT_NAME_RE.match(n):
                    violations += 1
                    if violations <= 10:
                        self.r.warning(f"命名违规: '{n}' ({self._lt(e.tag)}) [XSD: 字母开头, 仅含字母数字下划线]{self._li(s)}")
                if len(n) > IDENTIFIER_MAX_LEN and n not in xsd_long:
                    long_violations += 1
                    comp_path = self._bp(e)
                    self.r.error(f"IDENTIFIER 超长({len(n)}字符): '{n}' ({self._lt(e.tag)}, 限制{IDENTIFIER_MAX_LEN}){self._li(s)}")
                    if comp_path:
                        self.r.detail(f"         组件: {comp_path}")
        if violations == 0 and long_violations == 0:
            self.r.passed("命名规范符合 [a-zA-Z][a-zA-Z0-9_]*, maxLength=128")
        else:
            if violations > 0:
                self.r.warning(f"共 {violations} 个命名格式违规")
            if long_violations > 0:
                self.r.detail(f"共 {long_violations} 个 IDENTIFIER 超过 {IDENTIFIER_MAX_LEN} 字符 (XSD 已报 {len(xsd_long)} 个)")


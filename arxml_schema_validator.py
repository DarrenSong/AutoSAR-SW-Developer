#  入口
# ══════════════════════════════════════════════════════════════════════════════
def main():
    parser = argparse.ArgumentParser(
        description='AUTOSAR ARXML 规范校验工具 (基于 AUTOSAR_00046.xsd)')
    parser.add_argument('path', help='待校验 ARXML 文件或目录')
    parser.add_argument('--xsd', help='XSD Schema 文件路径 (默认自动查找)')
    parser.add_argument('-o', '--output', help='导出报告目录/文件')
    parser.add_argument('--pdf', action='store_true',
                        help='同时导出 PDF 格式报告 (需要 reportlab)')
    parser.add_argument('--batch', action='store_true',
                        help='批量校验目录下所有 ARXML 文件')
    parser.add_argument('--cache', help='保存校验结果到缓存文件 (JSON)')
    parser.add_argument('--from-cache', help='从缓存文件加载校验结果 (跳过校验)')
    args = parser.parse_args()

    target = args.path
    xsd_path = args.xsd

    if os.path.isdir(target):
        if args.batch:
            batch_validate(target, xsd_path, args.output or "", pdf=args.pdf)
        else:
            # 查找目录下的 arxml 文件
            arxml_files = [f for f in os.listdir(target) if f.lower().endswith('.arxml')]
            if len(arxml_files) == 1:
                target = os.path.join(target, arxml_files[0])
            else:
                print(f"目录下有 {len(arxml_files)} 个 ARXML 文件, 请使用 --batch 批量校验:")
                for f in arxml_files:
                    print(f"  - {f}")
                sys.exit(1)

    if not os.path.isfile(target):
        print(f"错误: 文件不存在: {target}")
        sys.exit(1)

    v = AutosarSchemaValidator(target, xsd_path)

    # 从缓存加载结果 (跳过校验)
    if args.from_cache:
        print(f"\n从缓存加载校验结果: {args.from_cache}")
        v.r.load_cache(args.from_cache)
        r = v.r
        v._report(0)
    else:
        r = v.validate()
        # 保存缓存
        if args.cache:
            v.r.save_cache(args.cache)
            print(f"\n校验结果已缓存: {args.cache}")

    if args.output:
        # 判断是目录还是文件: 已存在的目录、以分隔符结尾、或无扩展名均视为目录
        is_dir = os.path.isdir(args.output) or args.output.endswith(os.sep) or args.output.endswith('/') or '.' not in os.path.basename(args.output)
        if is_dir:
            os.makedirs(args.output, exist_ok=True)
            base = os.path.splitext(os.path.basename(target))[0]
            txt_out = os.path.join(args.output, f"{base}_validation_report.txt")
        else:
            txt_out = args.output
        v.export_txt(txt_out)
        if args.pdf:
            if is_dir:
                pdf_out = os.path.join(args.output, f"{base}_validation_report.pdf")
            else:
                pdf_out = os.path.splitext(txt_out)[0] + '.pdf'
            v.export_pdf(pdf_out)
    elif args.pdf:
        # 仅指定 --pdf 未指定 -o 时, 输出到当前目录
        base = os.path.splitext(os.path.basename(target))[0]
        pdf_out = f"{base}_validation_report.pdf"
        v.export_pdf(pdf_out)

    sys.exit(0 if r.is_valid else 1)


if __name__ == "__main__":
    main()

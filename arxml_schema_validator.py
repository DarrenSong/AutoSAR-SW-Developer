    def _check_unused_data_element(self):
        """检查未使用的数据元素 (Vector 40224) - 设计建议"""
        # 构建所有 DATA-ELEMENT 引用集合
        used_elements = set()
        
        # 1) 收集所有 DATA-ELEMENT-REF 引用
        for ref in self.root.iter(self._ns("DATA-ELEMENT-REF")):
            if ref.text:
                used_elements.add(ref.text.strip())
        
        # 2) 收集所有 TARGET-DATA-PROTOTYPE-REF
        for ref in self.root.iter(self._ns("TARGET-DATA-PROTOTYPE-REF")):
            if ref.text:
                used_elements.add(ref.text.strip())
        
        # 3) 收集所有 VARIABLE-DATA-PROTOTYPE-REF
        for ref in self.root.iter(self._ns("VARIABLE-DATA-PROTOTYPE-REF")):
            if ref.text:
                used_elements.add(ref.text.strip())
        
        # 4) 检查 SENDER-RECEIVER-INTERFACE 中的 DATA-ELEMENT
        unused_count = 0
        unused_list = []
        for iface in self.root.iter(self._ns("SENDER-RECEIVER-INTERFACE")):
            iface_name = self._sn(iface)
            for de_container in [iface.find(self._ns("DATA-ELEMENTS"))]:
                if de_container is None:
                    continue
                for de in de_container.findall(self._ns("VARIABLE-DATA-PROTOTYPE")):
                    de_name = self._sn(de)
                    # 构建可能的路径
                    iface_path = self._bp(iface)
                    de_path = f"{iface_path}/{de_name}"
                    
                    if de_path not in used_elements:
                        unused_count += 1
                        if len(unused_list) < 10:
                            unused_list.append((iface_name, de_name))
        
        if unused_count == 0:
            self.r.passed("所有数据元素均被使用")
        else:
            # 作为提示/警告输出
            for iface_name, de_name in unused_list:
                self.r.warning(f"[警告 40224] Interface '{iface_name}' 的数据元素 '{de_name}' 未被任何端口连接器引用")
            if unused_count > 10:
                self.r.warning(f"[警告 40224] 共 {unused_count} 个未使用的数据元素")

    @staticmethod
    def _nm_strip_dg_r_suffix(port_sn: str) -> str:
        """去掉委托端口后缀: Foo_DG_R / Foo_DG_DG_R / Foo_DG_DG_DG_R -> Foo"""
        return re.sub(r"(?:_DG)+_R$", "", port_sn or "")

    @staticmethod
    def _nm_ref_tail(elem) -> str:
        """取 REF 文本最后一段 SHORT-NAME"""
        if elem is None or not elem.text:
            return ""
        return elem.text.strip().split("/")[-1]

    def _nm_ensure_de(self, comp_de_comm, comp_name, de_name):
        if not de_name:
            return None
        if comp_name not in comp_de_comm:
            comp_de_comm[comp_name] = {}
        if de_name not in comp_de_comm[comp_name]:
            comp_de_comm[comp_name][de_name] = {"transmitters": set(), "receivers": set()}
        return comp_de_comm[comp_name][de_name]

    def _check_nm_communication(self):
        """检查 N:M 通信模式 (Vector 40329) - Vector RTE 约束

        N:M 模式: 同一数据元素被多个发送者发送到多个接收者
        Vector 要求: 所有发送者必须有完全相同的接收者集合
        典型场景: 冗余设计 DG_R 端口与主路径同时驱动同一数据元素
        """
        # comp_name -> {de_name -> {transmitters: set, receivers: set}}
        comp_de_comm = {}

        for comp in self.root.iter(self._ns("COMPOSITION-SW-COMPONENT-TYPE")):
            comp_name = self._sn(comp)
            connectors = comp.find(self._ns("CONNECTORS"))
            if connectors is None:
                continue

            # ---- ASSEMBLY: SWC → SWC ----
            for conn in connectors:
                conn_tag = self._lt(conn.tag)
                if conn_tag not in ("ASSEMBLY-SW-CONNECTOR", "ASSEMBLY-CONNECTOR"):
                    continue

                provider_iref = conn.find(self._ns("PROVIDER-IREF"))
                requester_iref = conn.find(self._ns("REQUESTER-IREF"))

                if provider_iref is not None and requester_iref is not None:
                    p_port_sn = self._nm_ref_tail(provider_iref.find(self._ns("TARGET-P-PORT-REF")))
                    r_port_sn = self._nm_ref_tail(requester_iref.find(self._ns("TARGET-R-PORT-REF")))
                    p_comp_sn = self._nm_ref_tail(provider_iref.find(self._ns("CONTEXT-COMPONENT-REF")))
                    r_comp_sn = self._nm_ref_tail(requester_iref.find(self._ns("CONTEXT-COMPONENT-REF")))
                    if not p_port_sn:
                        continue

                    info = self._nm_ensure_de(comp_de_comm, comp_name, p_port_sn)
                    if info is None:
                        continue
                    info["transmitters"].add(f"{p_comp_sn}/{p_port_sn}" if p_comp_sn else p_port_sn)
                    if r_port_sn:
                        info["receivers"].add(f"{r_comp_sn}/{r_port_sn}" if r_comp_sn else r_port_sn)
                else:
                    # 旧结构 PROVIDER/REQUESTER
                    provider = conn.find(self._ns("PROVIDER"))
                    requester = conn.find(self._ns("REQUESTER"))
                    if provider is None or requester is None:
                        continue

                    p_iref = provider.find(self._ns("P-PORT-IN-COMPOSITION-INSTANCE-REF"))
                    r_iref = requester.find(self._ns("R-PORT-IN-COMPOSITION-INSTANCE-REF"))
                    # IREF 是容器: CONTEXT-COMPONENT-REF + TARGET-*-PORT-REF
                    p_port_sn = self._nm_ref_tail(
                        p_iref.find(self._ns("TARGET-P-PORT-REF")) if p_iref is not None else None
                    )
                    r_port_sn = self._nm_ref_tail(
                        r_iref.find(self._ns("TARGET-R-PORT-REF")) if r_iref is not None else None
                    )
                    # 兼容极少数把路径直接写在 IREF 文本的写法
                    if not p_port_sn and p_iref is not None and (p_iref.text or "").strip():
                        p_port_sn = p_iref.text.strip().split("/")[-1]
                    if not r_port_sn and r_iref is not None and (r_iref.text or "").strip():
                        r_port_sn = r_iref.text.strip().split("/")[-1]

                    for com_spec in provider.iter(self._ns("NONQUEUED-SENDER-COM-SPEC")):
                        de_ref = com_spec.find(self._ns("DATA-ELEMENT-REF"))
                        if de_ref is None or not de_ref.text:
                            continue
                        de_name = de_ref.text.strip().split("/")[-1]
                        info = self._nm_ensure_de(comp_de_comm, comp_name, de_name)
                        if info is not None and p_port_sn:
                            info["transmitters"].add(p_port_sn)

                    for com_spec in requester.iter(self._ns("NONQUEUED-RECEIVER-COM-SPEC")):
                        de_ref = com_spec.find(self._ns("DATA-ELEMENT-REF"))
                        if de_ref is None or not de_ref.text:
                            continue
                        de_name = de_ref.text.strip().split("/")[-1]
                        info = self._nm_ensure_de(comp_de_comm, comp_name, de_name)
                        if info is not None and r_port_sn:
                            info["receivers"].add(r_port_sn)

            # ---- DELEGATION DG_R: 外边界 → 内 R-PORT（与 ASSEMBLY 并列，不可嵌套）----
            for conn in connectors:
                if self._lt(conn.tag) != "DELEGATION-SW-CONNECTOR":
                    continue
                conn_sn = self._sn(conn)
                # _DG_R / _DG_DG_R / _DG_DG_DG_R 的 SHORT-NAME 均含 "_DG_R" 子串
                if "_DG_R" not in conn_sn:
                    continue

                inner_port_iref = conn.find(self._ns("INNER-PORT-IREF"))
                outer_port_ref = conn.find(self._ns("OUTER-PORT-REF"))
                if inner_port_iref is None or outer_port_ref is None:
                    continue

                r_port_iref = inner_port_iref.find(self._ns("R-PORT-IN-COMPOSITION-INSTANCE-REF"))
                if r_port_iref is None:
                    continue  # P 侧委托不参与「额外发送者」判定

                # 正确解析: CONTEXT-COMPONENT-REF + TARGET-R-PORT-REF（不要读 IREF 容器 .text）
                r_comp_sn = self._nm_ref_tail(r_port_iref.find(self._ns("CONTEXT-COMPONENT-REF")))
                r_port_sn = self._nm_ref_tail(r_port_iref.find(self._ns("TARGET-R-PORT-REF")))
                if not r_port_sn:
                    continue

                outer_port_sn = self._nm_ref_tail(outer_port_ref)
                # 仅统计真正的 (_DG)+_R 外端口，避免普通委托误报
                if not re.search(r"(?:_DG)+_R$", outer_port_sn):
                    continue

                de_name = self._nm_strip_dg_r_suffix(outer_port_sn)
                info = self._nm_ensure_de(comp_de_comm, comp_name, de_name)
                if info is None:
                    continue

                info["transmitters"].add(f"Composition/{outer_port_sn}")
                info["receivers"].add(f"{r_comp_sn}/{r_port_sn}" if r_comp_sn else r_port_sn)

        # 检查 N:M: 多个发送者 AND 多个接收者（过滤空名）
        nm_issues = []
        for comp_name, de_dict in comp_de_comm.items():
            for de_name, info in de_dict.items():
                transmitters = {t for t in info["transmitters"] if t and t != "/"}
                receivers = {r for r in info["receivers"] if r and r != "/"}
                if len(transmitters) > 1 and len(receivers) > 1:
                    nm_issues.append((comp_name, de_name, transmitters, receivers))

        if not nm_issues:
            self.r.passed("无 N:M 通信模式")
        else:
            by_comp = {}
            for comp_name, de_name, transmitters, receivers in nm_issues:
                by_comp.setdefault(comp_name, []).append((de_name, transmitters, receivers))

            for comp_name, items in by_comp.items():
                self.r.error(
                    f"[Vector 40329] Composition '{comp_name}' 存在 {len(items)} 个 N:M 通信模式数据元素"
                )
                for idx, (de_name, transmitters, receivers) in enumerate(items, 1):
                    self.r.detail(f"  {idx}. 数据元素 '{de_name}':")
                    self.r.detail(
                        f"     发送者 ({len(transmitters)}): {', '.join(sorted(transmitters))}"
                    )
                    self.r.detail(
                        f"     接收者 ({len(receivers)}): {', '.join(sorted(receivers))}"
                    )
                self.r.detail("  [修复建议] N:M 模式通常由冗余设计 DG_R 端口引起，解决方案:")
                self.r.detail("    1. 确保所有发送者有完全相同的接收者集合")
                self.r.detail("    2. 或将多个接收者拆分为独立连接器，每个数据元素只有一个发送者")
                self.r.detail("    3. 或移除冗余的 DG_R 端口连接器")

    def _check_bitfield_contiguous(self):
        """检查 BITFIELD 位连续性 (Vector 40411) - Vector RTE 约束"""
        issues = 0
        checked = 0
        
        # 检查 COMPU-METHOD 中的 BITFIELD 定义
        for cm in self.root.iter(self._ns("COMPU-METHOD")):
            cm_name = self._sn(cm)
            category = cm.findtext(self._ns("CATEGORY"), "")
            
            # 只检查 BITFIELD 类型
            if category.upper() != "BITFIELD_TEXTTABLE":
                continue
            
            # 获取 COMPU-INTERNAL-TO-PHYS 中的掩码定义
            for int_to_phys in cm.iter(self._ns("COMPU-INTERNAL-TO-PHYS")):
                for compu_scale in int_to_phys.iter(self._ns("COMPU-SCALE")):
                    # 检查 MASK 元素
                    mask_elem = compu_scale.find(self._ns("MASK"))
                    if mask_elem is None or not mask_elem.text:
                        continue
                    
                    mask_text = mask_elem.text.strip()
                    
                    # 解析 MASK 值 (可能是 0b 二进制或十六进制)
                    try:
                        if mask_text.startswith('0b') or mask_text.startswith('0B'):
                            mask_val = int(mask_text, 2)
                        elif mask_text.startswith('0x') or mask_text.startswith('0X'):
                            mask_val = int(mask_text, 16)
                        else:
                            mask_val = int(mask_text)
                    except ValueError:
                        continue
                    
                    if mask_val == 0:
                        continue
                    
                    checked += 1
                    
                    # 检查掩码位是否连续
                    # 方法: 找到最高位和最低位, 检查中间是否全是1
                    # 例如: 0b111 (连续), 0b101 (不连续)
                    temp = mask_val
                    # 找到最低位的1
                    lowest_bit = temp & (-temp)
                    # 找到最高位的1
                    highest_bit = 1
                    while highest_bit < temp:
                        highest_bit <<= 1
                    
                    # 连续掩码应该是: 从 lowest_bit 到 highest_bit 全是1
                    # 例如: lowest=1, highest=4 -> 连续掩码应该是 0b1111 = 15
                    expected_contiguous = highest_bit - 1  # 0b1111 = 15 (bits 0-3)
                    # 但需要考虑 lowest_bit 可能不是 1
                    # 正确方法: 连续掩码 = ((1 << n) - 1) << shift
                    # 其中 n 是1的个数, shift 是最低位位置
                    
                    # 更简单的方法: 如果掩码连续, 那么 mask_val >> lowest_bit_pos 应该是 (1 << n) - 1
                    lowest_bit_pos = 0
                    temp2 = lowest_bit
                    while temp2 > 1:
                        temp2 >>= 1
                        lowest_bit_pos += 1
                    
                    shifted = mask_val >> lowest_bit_pos
                    # 检查 shifted 是否是 (1 << n) - 1 形式
                    if (shifted & (shifted + 1)) != 0:
                        issues += 1
                        if issues <= 10:
                            vt = compu_scale.find(self._ns("COMPU-CONST"))
                            vt_val = vt.findtext(self._ns("VT"), "?") if vt is not None else "?"
                            scale_label = compu_scale.findtext(self._ns("SHORT-LABEL"), "?")
                            self.r.warning(f"[Vector 40411] CompuMethod '{cm_name}' BITFIELD 掩码 {mask_text} 位不连续, Scale='{scale_label}', VT='{vt_val}'{self._li(compu_scale)}")
        
        if checked == 0:
            self.r.info("无 BITFIELD 定义")
        elif issues == 0:
            self.r.passed(f"{checked} 个 BITFIELD 掩码位连续")

    # ══════════════════════════════════════════════════════════════════════════
    #  报告输出
    # ══════════════════════════════════════════════════════════════════════════
    def _report(self, elapsed=0):
        r = self.r
        print(f"\n{'='*72}")
        print(f"  校验结果汇总")
        print(f"{'='*72}")
        print(f"  检查项: {r.total_count}  通过: {r.passed_count}  "
              f"错误: {len(r.errors)}  警告: {len(r.warnings)}  耗时: {elapsed:.1f}s")
        if r.errors:
            print(f"\n--- 错误 ({len(r.errors)}) ---")
            for i, e in enumerate(r.errors, 1):
                print(f"  [ERR {i:3d}] {e}")
                hint = r.get_fix_hint(e)
                if hint:
                    print(f"           -> {hint}")
        if r.warnings:
            print(f"\n--- 警告 ({len(r.warnings)}) ---")
            for i, w in enumerate(r.warnings, 1):
                print(f"  [WRN {i:3d}] {w}")
                hint = r.get_fix_hint(w)
                if hint:
                    print(f"           -> {hint}")
        if r.infos:
            print(f"\n--- 信息 ({len(r.infos)}) ---")
            for i, x in enumerate(r.infos, 1):
                print(f"  [INF {i:3d}] {x}")
        print(f"\n{'='*72}")
        if r.is_valid:
            print(f"  结论: 文件基本符合 AUTOSAR 规范 ({len(r.warnings)} 个警告)")
        else:
            print(f"  结论: 文件存在 {len(r.errors)} 个错误, 需修复!")
        print(f"{'='*72}\n")


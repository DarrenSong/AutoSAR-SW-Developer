    def _check_dest(self):
        unknown = 0
        mismatch = 0
        missing_dest = 0
        path_format_violations = 0
        ref_path_re = re.compile(r'^/?[a-zA-Z][a-zA-Z0-9_]{0,127}(/[a-zA-Z][a-zA-Z0-9_]{0,127})*$')
        for e in self.root.iter():
            t = self._lt(e.tag)
            if t.endswith("-REF") or t.endswith("-TREF"):
                # P1a: REF 必须带 DEST 属性
                d = e.get("DEST")
                if d is None:
                    missing_dest += 1
                    if missing_dest <= 10:
                        owner = self._owner(e)
                        loc = f" 组件: '{owner}'" if owner else ""
                        self.r.warning(f"{t} 缺少 DEST 属性 (XSD: use='required'){self._li(e)}{loc}")
                elif d not in VALID_DEST_TYPES:
                    unknown += 1
                    if unknown <= 5:
                        self.r.warning(f"未知 DEST: '{d}' ({t}){self._li(e)}")
                elif e.text and e.text.strip():
                    rp = e.text.strip()
                    # P2d: REF 路径格式校验
                    if not ref_path_re.match(rp):
                        path_format_violations += 1
                        if path_format_violations <= 10:
                            self.r.warning(f"REF 路径格式违规: '{rp[:60]}' ({t}){self._li(e)}")
                    at = self.path_tag.get(rp)
                    if at is None:
                        # 使用 path_last 索引快速查找
                        rl = rp.split('/')[-1]
                        if rl in self.path_last:
                            # 取第一个匹配的路径的类型
                            first_path = next(iter(self.path_last[rl]))
                            at = self.path_tag.get(first_path)
                    if at and at != d:
                        al = DEST_ALIASES.get(d, set())
                        if at not in al:
                            mismatch += 1
                            # 查找当前 REF 所属组件的 SHORT-NAME
                            owner_sn = self._owner(e)
                            loc = f" 组件: '{owner_sn}'" if owner_sn else ""
                            self.r.error(
                                f"DEST 不匹配: {t} DEST='{d}' 实际='{at}' 路径='{rp}'{loc}{self._li(e)}")

        if unknown == 0:
            self.r.passed("DEST 类型均合法")
        if mismatch == 0:
            self.r.passed("DEST 与实际类型一致")
        if missing_dest == 0:
            self.r.passed("REF/TREF 均带 DEST 属性")
        elif missing_dest > 10:
            # 直接追加到上一条warning, 避免detail()挂到error上
            if self.r.warnings:
                self.r.warnings[-1] += f'\n  (共 {missing_dest} 处缺少 DEST 属性, 仅显示前 10 条)'

